//! The soft beep: what a skipped sentence sounds like.
//!
//! The family's failure rule is "one attempt, soft beep, next sentence" —
//! the listener must hear that something was skipped, but the beep must not
//! be a scare. So: a short sine at a gentle pitch, well under full scale,
//! faded in and out so the envelope itself never clicks.

/// Seconds the beep lasts.
pub const BEEP_SECONDS: f64 = 0.15;
/// Pitch: clearly a tone, not an alert.
pub const BEEP_HZ: f64 = 660.0;
/// Peak amplitude, out of i16's 32 767 — about a fifth of full scale.
pub const BEEP_AMPLITUDE: i16 = 6_000;
/// Fade length at each end, in seconds. Without it, the beep's own start and
/// end are step discontinuities — clicks generated by us, not the device.
const FADE_SECONDS: f64 = 0.01;

/// Mono beep samples at `sample_rate`.
pub fn soft_beep(sample_rate: u32) -> Vec<i16> {
    let rate = sample_rate.max(1) as f64;
    let frames = (rate * BEEP_SECONDS).round() as usize;
    let fade = (rate * FADE_SECONDS).max(1.0) as usize;
    (0..frames)
        .map(|i| {
            let t = i as f64 / rate;
            let envelope = if i < fade {
                i as f64 / fade as f64
            } else if i >= frames.saturating_sub(fade) {
                (frames - i) as f64 / fade as f64
            } else {
                1.0
            };
            let value =
                (t * BEEP_HZ * 2.0 * std::f64::consts::PI).sin() * envelope * BEEP_AMPLITUDE as f64;
            value as i16
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_beep_is_short_quiet_and_faded() {
        let beep = soft_beep(48_000);
        assert_eq!(beep.len(), 7_200, "0.15 s at 48 kHz");
        let peak = beep.iter().map(|s| s.abs()).max().unwrap_or(0);
        assert!(peak <= BEEP_AMPLITUDE, "peak {peak} exceeds the ceiling");
        assert!(peak > 3_000, "peak {peak} — inaudibly quiet");
        // The fades: first and last non-zero samples are far off the peak.
        assert!(beep[0].abs() < 500);
        assert!(beep[beep.len() - 1].abs() < 500);
    }

    #[test]
    fn any_rate_produces_a_tone_of_the_right_length() {
        for rate in [8_000u32, 22_050, 48_000] {
            let beep = soft_beep(rate);
            let want = (rate as f64 * BEEP_SECONDS).round() as usize;
            assert_eq!(beep.len(), want, "rate {rate}");
        }
    }
}
